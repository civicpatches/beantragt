   * Pins for additional fixtures generated in individual tests.
   */
  private array $fixturePins = [];

  /**
   * Pins a fixture generated by the test.
   */
  public function pinFixture(array $manifest): void {
    $this->fixturePins[$manifest['key']][$manifest['version']] = [
      'sourceUri' => $manifest['sourceUri'],
      'sha256' => $manifest['sha256'],
    ];
  }

  /**
   * {@inheritdoc}
   */
  protected function contractMetadata(string $key, string $version): array {
    return $this->fixturePins[$key][$version] ?? self::CONTRACTS[$key][$version];
  }

