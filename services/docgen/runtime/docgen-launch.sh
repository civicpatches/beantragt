#!/bin/sh
# Starts docgen with only its own configuration in the environment. Used by
# the local DDEV service, where every .ddev/.env value is injected into every
# container. The production stack (deploy/docker-compose.docgen.yml) passes
# only docgen variables and starts the image's own command.
set -eu

exec env -i \
  PATH="$PATH" \
  HOME=/tmp \
  NODE_ENV=production \
  DOCGEN_TOKEN_FILE="${DOCGEN_TOKEN_FILE:-}" \
  DOCGEN_TOKENS_FILE="${DOCGEN_TOKENS_FILE:-}" \
  DOCGEN_TENANT="${DOCGEN_TENANT:-}" \
  DOCGEN_PORT="${DOCGEN_PORT:-3000}" \
  DOCGEN_MAX_DOCX_BYTES="${DOCGEN_MAX_DOCX_BYTES:-}" \
  DOCGEN_MAX_PDF_BYTES="${DOCGEN_MAX_PDF_BYTES:-}" \
  DOCGEN_MAX_XML_BYTES="${DOCGEN_MAX_XML_BYTES:-}" \
  DOCGEN_JOB_HEAP_MB="${DOCGEN_JOB_HEAP_MB:-}" \
  DOCGEN_JOB_TIMEOUT_MS="${DOCGEN_JOB_TIMEOUT_MS:-}" \
  DOCGEN_MAX_CONCURRENT_WORKERS="${DOCGEN_MAX_CONCURRENT_WORKERS:-}" \
  DOCGEN_MAX_QUEUED_WORKERS="${DOCGEN_MAX_QUEUED_WORKERS:-}" \
  DOCGEN_MAX_CONCURRENT_JOBS="${DOCGEN_MAX_CONCURRENT_JOBS:-}" \
  DOCGEN_MAX_QUEUED_JOBS="${DOCGEN_MAX_QUEUED_JOBS:-}" \
  DOCGEN_TENANT_MAX_CONCURRENT="${DOCGEN_TENANT_MAX_CONCURRENT:-}" \
  DOCGEN_TENANT_MAX_QUEUED="${DOCGEN_TENANT_MAX_QUEUED:-}" \
  DOCGEN_RETRY_AFTER_SECONDS="${DOCGEN_RETRY_AFTER_SECONDS:-}" \
  DOCGEN_HEALTH_TIMEOUT_MS="${DOCGEN_HEALTH_TIMEOUT_MS:-}" \
  DOCGEN_HEALTH_CACHE_MS="${DOCGEN_HEALTH_CACHE_MS:-}" \
  GOTENBERG_URL="${GOTENBERG_URL:-}" \
  GOTENBERG_USERNAME="${GOTENBERG_USERNAME:-}" \
  GOTENBERG_PASSWORD_FILE="${GOTENBERG_PASSWORD_FILE:-}" \
  GOTENBERG_TIMEOUT_MS="${GOTENBERG_TIMEOUT_MS:-}" \
  VERAPDF_URL="${VERAPDF_URL:-}" \
  VERAPDF_TIMEOUT_MS="${VERAPDF_TIMEOUT_MS:-}" \
  "$@"
